from __future__ import annotations

from fastapi import APIRouter, Depends, HTTPException, Query, Request
from sqlalchemy.orm import Session

from .. import auth, repository as repo
from ..database import get_db
from ..schemas import IotEventOut, IotSimulateIn, IotUpdateIn
from ..serializers import sim_iso
from ..services import engine, iot as iot_svc
from ..services.allocation import allocate
from ..services.domain import Params
from .common import Ctx

router = APIRouter(prefix="/api/iot", tags=["iot-simulated"])
NOTICE = "SIMULATED telemetry: no ESP32/RFID hardware is connected; events are generated by a software simulator."


@router.get("/events", response_model=list[IotEventOut])
def events(limit: int = Query(50, ge=1, le=200), db: Session = Depends(get_db)):
    """Recent simulated RFID/ESP32 events stored in PostgreSQL (newest first)."""
    return repo.list_iot_events(db, limit)


@router.get("/feed")
def feed(c: Ctx = Depends()):
    """Simulated in-transit container feed derived from the allocation plan and the simulation clock."""
    rows = iot_svc.feed_from_allocation(allocate(c.res, c.snap))
    for r in rows:
        r["last_update_sim"] = sim_iso(r.pop("minutes_before_sim_clock"))
    return {"notice": NOTICE, "containers": rows}


def _apply_in_transaction(db: Session, ev: dict) -> dict:
    """Apply one event and refresh the derived tables WITHOUT committing; the caller commits once so that a failure anywhere rolls the
    whole operation back (inventory, event log, alerts, priorities and allocations never disagree)."""
    try:
        out = repo.apply_iot_event(db, ev, commit=False)
    except repo.NotFound as e:
        raise HTTPException(404, str(e))
    except repo.Duplicate:
        raise HTTPException(409, detail={"code": "DUPLICATE_EVENT", "detail": "An event with this event_id was already applied; it was not applied again."})
    except iot_svc.IotError as e:
        raise HTTPException(422, str(e))
    repo.persist_baseline(db, commit=False)
    snap = repo.load_snapshot(db)
    res = engine.compute(snap, Params())
    item = next((i for i in res.items if i.location_id == ev["location_id"] and i.supply_id == ev["supply_id"]), None)
    a = out["applied"]
    return {"event_id": out["id"], "event_time": out["event_time"], "simulated": True, "notice": NOTICE,
            "stock_before": a.before, "stock_after": a.after, "clipped_at_zero": a.clipped,
            "item": None if item is None else {"days_left": round(item.days, 2), "status": item.status, "replenish_qty": item.qty},
            "location_status": next((l.status for l in res.locs if l.id == ev["location_id"]), None),
            "dashboard": {"critical_items": res.n_critical, "warning_items": res.n_warning, "risk_index": res.risk_index}}


def _ingest(db: Session, evs: list[dict]) -> list[dict]:
    try:
        results = [_apply_in_transaction(db, ev) for ev in evs]
        db.commit()
        return results
    except BaseException:
        db.rollback()
        raise


@router.post("/update")
def update(body: IotUpdateIn, request: Request, p: auth.Principal = Depends(auth.operator), db: Session = Depends(get_db)):
    """Ingest one simulated RFID/ESP32 event: stored in iot_events, inventory updated, alerts/priority/allocation refreshed (one transaction)."""
    ev = body.model_dump()
    out = _ingest(db, [ev])[0]
    auth.audit(p.username, "iot_update", "success", target=f"{ev['location_id']}/{ev['supply_id']}", ip=auth.get_client_ip(request),
               detail={"event_type": ev["event_type"], "quantity": ev["quantity"]})
    return out


@router.post("/simulate")
def simulate(body: IotSimulateIn, request: Request, p: auth.Principal = Depends(auth.operator), db: Session = Depends(get_db)):
    """Run the built-in ESP32/RFID simulator: generates `count` deterministic events and applies them all-or-nothing."""
    snap = repo.load_snapshot(db)
    res = engine.compute(snap, Params())
    seed = 1000 + len(repo.list_iot_events(db, 200))
    evs = iot_svc.generate_events(res, allocate(res, snap), body.count, seed)
    results = [r | {"request": ev} for r, ev in zip(_ingest(db, evs), evs)]
    auth.audit(p.username, "iot_simulate", "success", ip=auth.get_client_ip(request), detail={"events": len(results)})
    return {"notice": NOTICE, "generated": len(results), "events": results}


@router.post("/reset")
def reset(request: Request, p: auth.Principal = Depends(auth.admin), db: Session = Depends(get_db)):
    """Restore seeded inventory and delete simulated IoT events (administrator only; one transaction)."""
    try:
        n = repo.reset_inventory(db, commit=False)
        repo.persist_baseline(db, commit=False)
        db.commit()
    except BaseException:
        db.rollback()
        raise
    auth.audit(p.username, "inventory_reset", "success", ip=auth.get_client_ip(request), detail={"rows": n})
    return {"inventory_rows_restored": n}
