"""Render db/seed.sql from the deterministic synthetic dataset (fixed seed 2026).

Usage: python backend/scripts/generate_seed.py [output_path]
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "backend"))

from app import seed_data as S  # noqa: E402
from app.services.domain import ND, day_date  # noqa: E402


def q(v) -> str:
    return "'" + str(v).replace("'", "''") + "'"


def main(out: Path) -> None:
    ds = S.build_dataset()
    L = ["-- Deterministic FICTIONAL synthetic seed data (generated by backend/scripts/generate_seed.py, seed 2026).",
         "-- Prototype uses fictional synthetic logistics data and is intended for decision-support demonstration only.",
         "BEGIN;"]
    L.append("INSERT INTO supplies (id, base_daily_demand, weather_sensitivity, criticality_weight, sort_order) VALUES")
    L.append(",\n".join(f"({q(n)}, {b}, {s}, {S.CRITICALITY[n]}, {k})" for k, (n, b, s) in enumerate(S.SUPPLY_ROWS)) + ";")
    rows = []
    for k, (d, x, y) in enumerate(S.DEPOTS):
        lon, lat = S.xy_to_lonlat(x, y)
        rows.append(f"({q(d)}, {q(d.replace('_', ' ') + ' (fictional)')}, 'DEPOT', ST_SetSRID(ST_MakePoint({lon}, {lat}), 4326), 1, {k})")
    for k, (b, x, y, f, _) in enumerate(S.BASES):
        lon, lat = S.xy_to_lonlat(x, y)
        rows.append(f"({q(b)}, {q(b.replace('_', ' ') + ' (fictional)')}, 'FORWARD', ST_SetSRID(ST_MakePoint({lon}, {lat}), 4326), {f}, {k})")
    L.append("INSERT INTO locations (id, name, kind, geom, demand_factor, sort_order) VALUES\n" + ",\n".join(rows) + ";")
    L.append("INSERT INTO depots (location_id, depot_class, storage_capacity_units) VALUES\n" + ",\n".join(
        f"({q(d)}, {q(c)}, {cap})" for d, c, cap in [("Depot_A", "Primary depot", 400000), ("Depot_B", "Primary depot", 350000), ("Depot_C", "Secondary depot", 250000)]) + ";")
    L.append("INSERT INTO vehicles (id, depot_id, vehicle_type, capacity_units, available) VALUES\n" + ",\n".join(
        f"({q(i)}, {q(d)}, {q(t)}, {c}, {'true' if a else 'false'})" for i, d, c, a, t in S.VEHICLES) + ";")
    pos = {d: (x, y) for d, x, y in S.DEPOTS}
    pos.update({b: (x, y) for b, x, y, _, _ in S.BASES})
    rr = []
    for i, (rid, a, b, km, rd, sp) in enumerate(S.ROUTES):
        pts = ", ".join(f"{lon} {lat}" for lon, lat in S.route_polyline(pos[a], pos[b], i))
        rr.append(f"({q(rid)}, {q(a)}, {q(b)}, {km}, {rd}, {sp}, ST_GeomFromText('LINESTRING({pts})', 4326))")
    L.append("INSERT INTO routes (id, depot_id, destination_id, distance_km, road_condition, nominal_speed_kmh, geom) VALUES\n" + ",\n".join(rr) + ";")
    L.append("INSERT INTO terrain (route_id, terrain_type, difficulty, elevation_band, elevation_label) VALUES\n" + ",\n".join(
        f"({q(r)}, {q(t)}, {td}, {el}, {q(S.ELEVATION_LABELS[el])})" for r, t, td, el in S.TERRAIN) + ";")
    L.append("INSERT INTO weather (day_index, obs_date, severity_index, kind) VALUES\n" + ",\n".join(
        f"({d}, '{day_date(d).date().isoformat()}', {repr(w)}, '{'OBSERVED' if d < ND else 'OUTLOOK'}')" for d, w in enumerate(ds["weather"])) + ";")
    # consumption: 5 forward locations x 10 supplies x 110 days = 5,500 records
    chunk = []
    for (b, t), xs in ds["history"].items():
        for d, v in enumerate(xs):
            chunk.append(f"({q(b)}, {q(t)}, {d}, '{day_date(d).date().isoformat()}', {v})")
    for i in range(0, len(chunk), 500):
        L.append("INSERT INTO consumption (location_id, supply_id, day_index, consumption_date, quantity) VALUES\n" + ",\n".join(chunk[i:i + 500]) + ";")
    inv = [f"({q(b)}, {q(t)}, {s}, {sf}, {s})" for (b, t), (s, sf) in ds["stocks"].items()]
    inv += [f"({q(d)}, {q(t)}, {v}, 0, {v})" for (d, t), v in ds["depot_stock"].items()]
    L.append("INSERT INTO inventory (location_id, supply_id, stock, safety_stock, initial_stock) VALUES\n" + ",\n".join(inv) + ";")
    L.append("COMMIT;")
    out.write_text("\n".join(L) + "\n")
    print(f"wrote {out} ({out.stat().st_size // 1024} KiB); consumption records: {len(chunk)}")


if __name__ == "__main__":
    main(Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "db" / "seed.sql")
