#!/usr/bin/env python3
"""Generate docs/DATA_DICTIONARY.md from a migrated database (tables, columns, types, constraints) plus the provenance statements.

    DATABASE_URL=postgresql+psycopg://... python scripts/make_data_dictionary.py      # a throw-away, already migrated database
"""
import os, sys
from pathlib import Path
import psycopg

ROOT = Path(__file__).resolve().parents[1]
url = os.environ.get("DATABASE_URL", "").replace("postgresql+psycopg://", "postgresql://")
if not url:
    sys.exit("set DATABASE_URL to a migrated database")
PURPOSE = {
    "supplies": "The 10 supply classes: base daily demand, weather sensitivity, criticality weight, unit.",
    "locations": "Depots (sources) and forward bases (destinations) with PostGIS point geometry (SRID 4326). Fictional coordinates.",
    "depots": "Depot attributes (stock is in `inventory`).", "vehicles": "Fleet: home depot, capacity (units), availability.",
    "routes": "Corridors depot -> forward base: distance, nominal speed, road condition, terrain type/difficulty/elevation band, PostGIS line.",
    "terrain": "Terrain classes and difficulty used by routes.", "weather": "Simulated daily weather index per location (0 normal .. 1 severe), including the outlook.",
    "consumption": "Simulated daily consumption per location, supply and day (110 days of history).",
    "inventory": "Current stock, initial (seeded) stock and safety stock per location and supply. Only the CURRENT level is stored: there is no daily on-hand history.",
    "forecasts": "Stored forecast rows (value and 80% interval) per series and day, with the model that produced them.",
    "alerts": "Baseline alert table derived from inventory and forecasts.", "priority_scores": "Baseline priority scores and their components.",
    "allocations": "Baseline allocation plan rows (need, quantity, unmet, binding constraint).",
    "iot_events": "Ledger of simulated RFID/ESP32 inventory events (stock before/after). Optional `event_id` is an idempotency key.",
    "simulation_runs": "Saved What-If runs: parameters, before/after metrics, explanation.", "users": "Accounts (scrypt hashes only), role, active flag, token version.",
    "audit_log": "Security-relevant events; never contains passwords or tokens.", "schema_migrations": "Applied migrations with checksums.",
}
out = ["# Data dictionary\n", "*Generated by `scripts/make_data_dictionary.py` from the migrated schema (migrations 0001-0004). Provenance and limits are at the end.*\n"]
with psycopg.connect(url) as c:
    tables = [r[0] for r in c.execute("select table_name from information_schema.tables where table_schema='public' and table_type='BASE TABLE' and table_name not in ('spatial_ref_sys') order by 1")]
    for t in tables:
        out.append(f"## `{t}`\n\n{PURPOSE.get(t, '')}\n")
        out.append("| Column | Type | Null | Default / constraint |\n|---|---|---|---|")
        cols = c.execute("select column_name, data_type, udt_name, is_nullable, column_default from information_schema.columns where table_schema='public' and table_name=%s order by ordinal_position", (t,)).fetchall()
        for n, dt, udt, nul, d in cols:
            out.append(f"| {n} | {udt if dt == 'USER-DEFINED' else dt} | {'yes' if nul == 'YES' else 'no'} | {(d or '').replace('|', '/')[:60]} |")
        cons = c.execute("select conname, pg_get_constraintdef(oid) from pg_constraint where conrelid = %s::regclass order by contype, conname", (f"public.{t}",)).fetchall()
        if cons:
            out.append("\nConstraints: " + "; ".join(f"`{n}`: {d}" for n, d in cons) + "\n")
        else:
            out.append("")
out.append("""## Provenance, units and limits

| Data | Origin | Real or simulated | Notes |
|---|---|---|---|
| Locations, depots, vehicles, routes, terrain, weather, consumption, initial inventory | `backend/scripts/generate_seed.py` (deterministic, seed 2026) -> `db/seed.sql` | **Simulated, fictional** | Coordinates are fictional grid points. Units are abstract "units" per supply class; distances in km; speeds in km/h; times in hours/days. 5 forward locations x 10 supplies x 110 days of consumption. Nothing maps to a real place, unit or stock. |
| Weather index | same generator | **Simulated** | No weather service is connected. |
| Inventory events (`iot_events`) | the built-in software simulator or a user's API call | **Simulated** | No ESP32/RFID hardware exists in this project. |
| Forecasts, alerts, priorities, allocations, simulation runs | computed by the application | **Model/rule outputs** | Predictions and recommendations, not observations. |
| ISOMORPH benchmark | external, CC-BY-4.0 (ISOMORPH Sample), documented in `ml/DATA_CARD.md` | **Simulator-generated benchmark** (13-node US supply chain digital twin) | Not bundled. Used only to train/evaluate the shipped model artefacts. Results are not observations of any real operation, least of all Indian Army operations. |
| `Dataset_AI_Supply_Optimization.csv` | provided with the project | **Unknown provenance** | Profiled only (`ml/reports/supply_csv_profile.json`); not used for training, tuning or any displayed figure. No keys, dates or locations exist to form a time series. |
| Public geographic/terrain data | **none used** | - | Terrain classes in the scenario are fictional labels. No elevation or road dataset is bundled; the schema (PostGIS geometry columns) allows one to be added later. |
| Validated real-world operational observations | **none** | - | The project contains no such data. |

Units: stock and demand in abstract units/day; `days_left` in days; ETA in hours; risk indices 0-100; weather index 0-1.
""")
(ROOT / "docs" / "DATA_DICTIONARY.md").write_text("\n".join(out), encoding="utf-8")
print("wrote docs/DATA_DICTIONARY.md:", len(tables), "tables")
