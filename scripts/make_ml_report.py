#!/usr/bin/env python3
"""Generate docs/ML_EVALUATION_REPORT.md from the stored evaluation reports and artefact metadata (no number is typed by hand).

    python scripts/make_ml_report.py          # rewrites docs/ML_EVALUATION_REPORT.md
"""
import json, statistics
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
R = ROOT / "ml" / "reports"
bench = json.loads((R / "forecast_benchmark_eval.json").read_text())
scen = json.loads((R / "forecast_scenario_eval.json").read_text())
short = json.loads((R / "shortage_benchmark_eval.json").read_text())
fmeta = json.loads((ROOT / "ml/artifacts/forecast/v1/metadata.json").read_text())
smeta = json.loads((ROOT / "ml/artifacts/shortage/v1/metadata.json").read_text())
T = bench["test"]
pct = lambda x: f"{100 * x:.2f}%"
out = []
w = out.append

w("# ML evaluation report\n")
w("*Generated by `scripts/make_ml_report.py` from `ml/reports/*.json` and the artefact metadata. Benchmark data is simulator output; none of these figures describes real operations.*\n")
w("## Status of this evidence\n")
w("* **Benchmark (ISOMORPH) figures are quoted from the reports produced for V5/V6 and were NOT re-run in V7**: the dataset is not bundled and was not accessible. The leakage-free split/purge code is exercised by `ml/tests` (14 tests) and `backend/tests/test_ml_v6.py`; the numbers themselves are unverified by this release.")
w("* **Application-scenario holdout figures were re-computed in V6 from scratch and matched the shipped report exactly** (`ml/evaluate_app_series.py --no-promote`); V7 did not change any model or evaluation code.\n")
w("## Protocol\n")
w(f"* Forecasting benchmark: {T['n_rows']:,} test rows (50 items, forecast origins every {T['origins_stride']} days, horizons 1-30). Chronological split of the 52,560-day series; targets of each segment lie inside the segment (purge); hyper-parameters chosen on validation only; test evaluated once. Zero-demand handling: WAPE = sum|error| / sum|actual| (undefined only if all actuals are zero); MAPE excludes zero actuals and reports how many were excluded (0 here: the benchmark has no zero-demand days).")
w(f"* Scenario holdout: {scen['protocol']['rows']:,} rows (50 series, origins {scen['protocol']['origins'][0]}..{scen['protocol']['origins'][-1]}, horizons 1-30). {scen['protocol']['note']}.\n")
w("## 1. Benchmark, test segment (all horizons)\n")
w("| Model | MAE | RMSE | WAPE | Bias |\n|---|---|---|---|---|")
for k, v in sorted(T["overall"].items(), key=lambda kv: kv[1]["wape"]):
    w(f"| {k} | {v['mae']:.2f} | {v['rmse']:.2f} | {pct(v['wape'])} | {100 * v['bias']:+.2f}% |")
w("\nBy horizon bucket (WAPE):\n")
names = list(T["overall"])
w("| Horizon | " + " | ".join(names) + " |\n|---|" + "---|" * len(names))
for b, d in T["by_horizon_bucket"].items():
    w(f"| {b} | " + " | ".join(pct(d[n]["wape"]) if n in d else "-" for n in names) + " |")
ci = T["rel_wape_improvement_vs_baseline_95ci"]
w(f"\nBest simple baseline: **{T['best_baseline']}**. LightGBM's relative WAPE improvement over each competitor (95% bootstrap interval over items/origins): " + "; ".join(f"{k}: {pct(v[0])}..{pct(v[1])}" for k, v in ci.items()) + f". LightGBM beats the best baseline on {T['items_where_lightgbm_beats_best_baseline']} items. 80% interval coverage on test: {pct(T['interval_coverage']['test_overall'])}.\n")
w("**Reading:** on the benchmark the gradient-boosted model is better than every simple baseline and marginally better than Random Forest. This says nothing about the application's data, see §2.\n")
w("## 2. Application scenario holdout\n")
w("| Model | MAE | RMSE | WAPE (h1-30) |\n|---|---|---|---|")
for k, v in sorted(scen["overall"].items(), key=lambda kv: kv[1]["wape"]):
    w(f"| {k} | {v['mae']:.2f} | {v['rmse']:.2f} | {pct(v['wape'])} |")
w("\nBy horizon bucket (WAPE):\n")
sn = list(scen["overall"])
w("| Horizon | " + " | ".join(sn) + " |\n|---|" + "---|" * len(sn))
for b, d in scen["by_horizon_bucket"].items():
    w(f"| {b} | " + " | ".join(pct(d[n]["wape"]) if n in d else "-" for n in sn) + " |")
loc = {}
for key, d in scen["per_series_wape"].items():
    for m_, v in d.items():
        loc.setdefault(key.split("/")[0], {}).setdefault(m_, []).append(v)
w("\nBy location (mean of the series-level WAPE of the 10 supplies at each location):\n")
tm = ["statistical_ewma (existing)", "ml_weather_adapter"]
w("| Location | " + " | ".join(tm) + " |\n|---|" + "---|" * len(tm))
for l, d in sorted(loc.items()):
    w(f"| {l} | " + " | ".join(pct(statistics.mean(d[m_])) for m_ in tm) + " |")
p = scen["promotion"]
w(f"\n**Caveat:** the scenario history is generated from the statistical model's own structure, which favours it ({scen['protocol']['note'].split(';')[0]}).\n")
w("## 3. Model-promotion decision\n")
w(f"* Rule (documented in `ml/README.md`): promote the trained model only if on the scenario holdout (h1-14) it improves WAPE by at least 2% with the 95% interval above 0, it beats the best baseline on the benchmark with the interval above 0, and series-level interval coverage lies within 70-90%.")
w(f"* Decision recorded in the artefact metadata: **`{p['status']}`**. {p['reason']}.")
w("* Criteria: " + ", ".join(f"`{k}` = {v}" for k, v in p["criteria"].items()) + ".")
w(f"* **Default forecaster in the application: `ewma-weather-seasonal-v1` (statistical)**. `FORECAST_MODEL_MODE=auto` uses the trained model only when promoted; `ml` forces it with a visible fallback; the active model, its load time and any fallback are shown on the System page and in `/api/health/detail`.")
w(f"* Artefact: `{fmeta['model_name'] + '@' + fmeta['version']}` created {fmeta['created_utc']}, SHA-256 `{fmeta['model_sha256']}`.\n")
w("## 4. Shortage-onset model (benchmark only; not used for application status)\n")
tp = short["test_onset_population"]["lightgbm_calibrated"]
w(f"* Target: {short['label_definition']}; horizon {short['horizon_days']} days. Operating threshold {short['operating_point']['threshold']} ({short['operating_point']['rule']}).")
w(f"* Test, onset population (n={tp['n']:,}, {tp['positives']:,} positives, base rate {pct(tp['base_rate'])}): ROC-AUC {tp['roc_auc']:.3f}, PR-AUC {tp['pr_auc']:.3f}, Brier {tp['brier']:.4f}, ECE {tp['ece']:.4f}, precision {tp['precision']:.3f}.")
for k, v in short["test_all_days_context"].items():
    if not (isinstance(v, dict) and "roc_auc" in v):
        continue
    w(f"* Context baseline `{k}` (all item-days, n={v['n']:,}): ROC-AUC {v['roc_auc']:.3f}, PR-AUC {v['pr_auc']:.3f}, Brier {v['brier']:.4f}.")
w("* `feature_gain_importance` is dominated by the in-transit ratio; the report's own note says a stock-only variant (cover and demand statistics) is the fair comparison with a days-of-cover rule.")
w("* **Not integrated into inventory status**: its inputs (daily on-hand, in-transit, backlog histories) do not exist in the application's data. See `docs/SHORTAGE_MODEL_DECISION.md`. It is callable only on user-supplied benchmark-format records.\n")
w("## 5. Robustness checks (automated)\n")
w("Missing / short / non-finite / negative histories, mismatched known-factor vectors, intermittent (sparse) series, invalid horizons (HTTP 422), unseen locations and supplies (HTTP 404), truncated, corrupt, symlinked, wrongly-pinned and schema-incompatible artefacts, path traversal in the version pointer, training-vs-inference feature parity for every horizon, determinism: `backend/tests/test_ml_v6.py`, `test_ml_artifacts.py`, `test_ml_core.py`, `test_ml_api.py`.\n")
w("## 6. What this report does not show\n")
w("No evaluation on real operational data, no cost or shortage-reduction measurement, no calibration of the business-rule thresholds, no evaluation of the shortage model on this application's data.\n")
(ROOT / "docs" / "ML_EVALUATION_REPORT.md").write_text("\n".join(out), encoding="utf-8")
print("wrote docs/ML_EVALUATION_REPORT.md")
